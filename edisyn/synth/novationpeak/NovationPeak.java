    public String revisePatchName(String name)
        {
        name = super.revisePatchName(name);
        if (name == null) name = "";
        char[] chars = (name + "                ").substring(0, NAME_LENGTH).toCharArray();
        for (int i = 0; i < chars.length; i++)
            if (chars[i] < 32 || chars[i] > 126) chars[i] = ' ';
        return new String(chars);
        }

    public String getPatchName(Model model) { return model.get("name", "Init Patch").trim(); }

    // ======================================================================================
    // Parse / emit

    static boolean hasPeakHeader(byte[] data)
        {
        if (data == null || data.length < 9 || (data[0] & 0xFF) != 0xF0) return false;
        for (int i = 0; i < HEADER.length; i++)
            if (data[1 + i] != HEADER[i]) return false;
        return true;
        }

    static boolean isPatchMessage(byte[] data)
        {
        return hasPeakHeader(data) && data.length == PATCH_LENGTH && (data[PATCH_LENGTH - 1] & 0xFF) == 0xF7
            && (data[8] == CMD_EDIT_BUFFER || data[8] == CMD_STORED);
        }

    public int parse(byte[] data, boolean fromFile)
        {
        if (!isPatchMessage(data)) return PARSE_FAILED;

        if (data[8] == CMD_STORED)
            {
            int bank = data[BANK_OFFSET] - 1, slot = data[SLOT_OFFSET];
            if (bank < 0 || bank > 3 || slot < 0 || slot > 127) return PARSE_FAILED;
            model.set("bank", bank);
            model.set("number", slot);
            }

        char[] name = new char[NAME_LENGTH];
        for (int i = 0; i < NAME_LENGTH; i++) name[i] = (char)data[NAME_OFFSET + i];
        model.set("name", new String(name));

        for (NovationPeakParams.P p : NovationPeakParams.PARAMS)
            {
            int b0 = data[p.offset];
            if (p.u8)
                {
                int b1 = data[p.offset + 1];
                model.set(p.key, (b0 << 1) | ((b1 >> 6) & 1));
                model.set(extraBitsKey(p.key), b1 & 0x3F);
                }
            else
                {
                model.set(p.key, b0);
                }
            }
        for (int offset : NovationPeakParams.HIDDEN_OFFSETS)
            model.set(hiddenKey(offset), data[offset]);

        // No revise(): stored values outside the chart range (e.g. Arp Chance 0 in FW 1.x
        // patches) must survive so the patch round-trips byte for byte.
        return PARSE_SUCCEEDED;
        }

    /** The 527-byte patch message for the current model, as an edit-buffer write or a stored-slot dump. */
    byte[] buildPatch(int command, int bank, int slot)
        {
        byte[] d = new byte[PATCH_LENGTH];
        d[0] = (byte)0xF0;
        System.arraycopy(HEADER, 0, d, 1, HEADER.length);
        d[8] = (byte)command;
        if (command == CMD_STORED) { d[BANK_OFFSET] = (byte)(bank + 1); d[SLOT_OFFSET] = (byte)slot; }

        String name = revisePatchName(model.get("name", ""));
        for (int i = 0; i < NAME_LENGTH; i++) d[NAME_OFFSET + i] = (byte)name.charAt(i);

        for (NovationPeakParams.P p : NovationPeakParams.PARAMS)
            {
            int v = model.get(p.key, p.def);
            if (p.u8)
                {
                d[p.offset] = (byte)((v >> 1) & 0x7F);
                d[p.offset + 1] = (byte)(((v & 1) << 6) | (model.get(extraBitsKey(p.key), 0) & 0x3F));
                }
            else
                {
                d[p.offset] = (byte)(v & 0x7F);
                }
            }
        for (int offset : NovationPeakParams.HIDDEN_OFFSETS)
            d[offset] = (byte)(model.get(hiddenKey(offset), 0) & 0x7F);
        d[PATCH_LENGTH - 1] = (byte)0xF7;
        return d;
        }

    public Object[] emitAll(Model tempModel, boolean toWorkingMemory, boolean toFile)
        {
        if (tempModel == null) tempModel = getModel();
        if (toWorkingMemory)
            return new Object[] { buildPatch(CMD_EDIT_BUFFER, 0, 0) };
        if (toFile)
            return new Object[] { buildPatch(CMD_STORED, tempModel.get("bank", 0), tempModel.get("number", 0)) };

        // Anything else is Edisyn asking for a write to a slot on the synth: never.
        refuseWrite();
        return new Object[0];
        }

    public byte[] emit(Model tempModel, boolean toWorkingMemory, boolean toFile)
        {
        Object[] out = emitAll(tempModel, toWorkingMemory, toFile);
        return out.length == 0 ? null : (byte[])out[0];
        }

    void refuseWrite()
        {
        if (testMode) { testDialogs.add(WRITE_REFUSED_TITLE); return; }
        if (SwingUtilities.isEventDispatchThread() && !GraphicsEnvironment.isHeadless())
            showSimpleMessage(WRITE_REFUSED_TITLE, WRITE_REFUSED_TEXT);
        else
            System.err.println("NovationPeak: " + WRITE_REFUSED_TITLE);
        }

    // ======================================================================================
    // Single-parameter changes

    public Object[] emitAll(String key)
        {
        NovationPeakParams.P p = BY_KEY.get(key);
        if (p == null)
            {
            // "name" and anything else without a CC/NRPN go as a whole patch.
            if (key.equals("name")) scheduleDump();
            return new Object[0];
            }
        if (p.route == NovationPeakParams.ROUTE_NONE) return new Object[0];

        int v = model.get(key, p.def);
        if (dumpPerChange || p.route == NovationPeakParams.ROUTE_DUMP || v < p.chartMin || v > p.chartMax)
            {
            scheduleDump();   // out-of-chart values ("raw N" choices) are never sent as CC/NRPN
            return new Object[0];
            }
        return controlMessages(p, v, getChannelOut());
        }

    /** The CC/NRPN messages for one parameter, exactly as peak-editor's ControlGuard builds them. */
    static Object[] controlMessages(NovationPeakParams.P p, int v, int channel)
        {
        try
            {
            switch (p.route)
                {
                case NovationPeakParams.ROUTE_CC:
                    return new Object[] { new ShortMessage(ShortMessage.CONTROL_CHANGE, channel, p.cc, v & 0x7F) };
                case NovationPeakParams.ROUTE_CC_PAIR:   // MSB first (value >> 1), then LSB CC with 0x40 if the low bit is set
                    return new Object[] {
                        new ShortMessage(ShortMessage.CONTROL_CHANGE, channel, p.cc, (v >> 1) & 0x7F),
                        new ShortMessage(ShortMessage.CONTROL_CHANGE, channel, p.ccLsb, (v & 1) != 0 ? 0x40 : 0) };
                case NovationPeakParams.ROUTE_NRPN:      // 99, 98, 6 only: never CC 38
                    return new Object[] {
                        new ShortMessage(ShortMessage.CONTROL_CHANGE, channel, 99, p.nrpnMsb & 0x7F),
                        new ShortMessage(ShortMessage.CONTROL_CHANGE, channel, 98, p.nrpnLsb & 0x7F),
                        new ShortMessage(ShortMessage.CONTROL_CHANGE, channel, 6, v & 0x7F) };
                default:
                    return new Object[0];
                }
            }
        catch (InvalidMidiDataException e)
            {
            return new Object[0];
            }
        }

    void scheduleDump()
        {
        if (!getSendMIDI() && captureOutgoing == null) return;
        dumpTimer.restart();
        }

    /** Sends the pending whole-patch edit-buffer write now (the debounce timer calls this). */
    void sendPendingDump()
        {
        dumpTimer.stop();
        tryToSendMIDI(emitAll(getModel(), true, false));
        }


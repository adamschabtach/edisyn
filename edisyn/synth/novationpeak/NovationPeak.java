    public boolean gatherPatchInfo(String title, Model change, boolean writing)
        {
        if (writing) { refuseWrite(); return false; }
        if (testMode) return true;

        JComboBox<String> bank = new JComboBox<>(BANKS);
        bank.setEditable(false);
        bank.setSelectedIndex(Math.max(0, Math.min(3, model.get("bank", 0))));
        JTextField number = new SelectedTextField("" + model.get("number", 0), 3);

        while (true)
            {
            boolean result = showMultiOption(this, new String[] { "Bank", "Patch Number" },
                new JComponent[] { bank, number }, title, "Enter the bank and patch number (0-127).");
            if (!result) return false;

            int n;
            try { n = Integer.parseInt(number.getText().trim()); }
            catch (NumberFormatException e) { showSimpleError(title, "The patch number must be an integer 0 ... 127"); continue; }
            if (n < 0 || n > 127) { showSimpleError(title, "The patch number must be an integer 0 ... 127"); continue; }

            change.set("bank", bank.getSelectedIndex());
            change.set("number", n);
            return true;
            }
        }

    public String getPatchLocationName(Model model)
        {
        if (!model.exists("number") || !model.exists("bank")) return null;
        return BANKS[Math.max(0, Math.min(3, model.get("bank")))] + String.format("%03d", model.get("number"));
        }

    public Model getNextPatchLocation(Model model)
        {
        int bank = model.get("bank", 0), number = model.get("number", 0) + 1;
        if (number > 127) { number = 0; bank = (bank + 1) % BANKS.length; }
        Model next = buildModel();
        next.set("bank", bank);
        next.set("number", number);
        return next;
        }

    public boolean patchLocationEquals(Model a, Model b)
        {
        return a.get("bank", -1) == b.get("bank", -2) && a.get("number", -1) == b.get("number", -2);
        }


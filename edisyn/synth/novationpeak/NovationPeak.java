    static byte[] request(int command, int bank, int slot)
        {
        byte[] d = new byte[REQUEST_LENGTH];
        d[0] = (byte)0xF0;
        System.arraycopy(HEADER, 0, d, 1, HEADER.length);
        d[8] = (byte)command;
        d[BANK_OFFSET] = (byte)bank;
        d[SLOT_OFFSET] = (byte)slot;
        d[REQUEST_LENGTH - 1] = (byte)0xF7;
        return d;
        }


    public String revisePatchName(String name)
        {
        name = super.revisePatchName(name);
        if (name == null) name = "";
        StringBuilder b = new StringBuilder();
        for (int i = 0; i < name.length() && b.length() < RolandXV5050Params.NAME_LENGTH; i++)
            {
            char c = name.charAt(i);
            b.append(c >= 32 && c <= 126 ? c : ' ');
            }
        while (b.length() < RolandXV5050Params.NAME_LENGTH) b.append(' ');
        return b.toString();
        }

    /** Roland device IDs run 17...32 on the panel, 0x10...0x1F on the wire. */
    public byte getID()
        {
        try
            {
            byte b = Byte.parseByte(tuple.id);
            if (b >= 17 && b <= 32) return (byte)(b - 17 + 0x10);
            }
        catch (NullPointerException e) { }                        // the tuple isn't built yet
        catch (NumberFormatException e) { Synth.handleException(e); }
        return (byte)0x10;
        }

    public String reviseID(String id)
        {
        try
            {
            int val = Integer.parseInt(id);
            if (val < 17) val = 17;
            if (val > 32) val = 32;
            return "" + val;
            }
        catch (NumberFormatException ex) { return "" + (getID() - 0x10 + 17); }
        }

    // ======================================================================================
    // Parsing

    /** Which of the nine blocks have arrived in the dump being assembled. */
    int parsedBlocks = 0;
    static final int ALL_BLOCKS = (1 << 9) - 1;

    public int parse(byte[] data, boolean fromFile)
        {
        byte[][] messages = RolandXV5050Sysex.split(data);
        if (messages.length == 0) return PARSE_FAILED;
        if (messages.length == 1) return parseOne(messages[0], fromFile);

        // A file, or a dump that arrived as one buffer. Work through it in order, and
        // ignore messages that are not patch blocks: files written by other editors may
        // carry blocks the XV-5050 patch editor does not model.
        parsedBlocks = 0;
        int result = PARSE_INCOMPLETE, claimed = 0;
        for (byte[] m : messages)
            {
            if (RolandXV5050Rec.blockIndex(m) < 0) continue;
            claimed++;
            result = parseOne(m, fromFile);
            if (result == PARSE_FAILED) return PARSE_FAILED;
            }
        return claimed == 0 ? PARSE_FAILED : result;
        }

    int parseOne(byte[] data, boolean fromFile)
        {
        if (!RolandXV5050Sysex.isDT1(data)) return PARSE_FAILED;
        if (!RolandXV5050Sysex.checksumOK(data))
            System.err.println("RolandXV5050.parse(): bad checksum at address "
                + Integer.toHexString(RolandXV5050Sysex.addressOf(data)) + "; parsing anyway.");

        int address = RolandXV5050Sysex.addressOf(data);
        int size = data.length - RolandXV5050Sysex.DT1_OVERHEAD;

        int base = patchBaseOf(address, size);
        if (base < 0) return PARSE_FAILED;

        int blockIndex = blockIndexOf(address - base, size);
        if (blockIndex < 0) return PARSE_FAILED;

        RolandXV5050Params.Block block = RolandXV5050Params.PATCH[blockIndex];
        int start = RolandXV5050Sysex.ADDRESS_OFFSET + 4;

        if (block == COMMON_BLOCK)
            {
            StringBuilder name = new StringBuilder();
            for (int i = 0; i < RolandXV5050Params.NAME_LENGTH; i++)
                {
                char c = (char)(data[start + i] & 0x7F);
                name.append(c >= 32 && c <= 126 ? c : ' ');
                }
            model.set("name", name.toString());
            }

        for (RolandXV5050Params.P p : block.params)
            {
            int v = RolandXV5050Sysex.decode(p, data, start);
            if (v > p.max)
                {
                // A safety net: nothing in the address map should exceed its range.
                System.err.println("RolandXV5050.parse(): " + p.key + " = " + v
                    + " exceeds " + p.max + "; clamped.");
                v = p.max;
                }
            if (v < p.min) v = p.min;
            model.set(p.key, v);
            }

        // A user address tells us where the patch lives.
        if (base >= RolandXV5050Sysex.USER_PATCH)
            {
            int n = (base - RolandXV5050Sysex.USER_PATCH) / RolandXV5050Sysex.USER_STRIDE;
            if (n >= 0 && n < PATCHES_PER_BANK)
                {
                model.set("bank", BANK_USER);
                model.set("number", n);
                }
            }

        parsedBlocks |= (1 << blockIndex);
        if (parsedBlocks == ALL_BLOCKS)
            {
            parsedBlocks = 0;
            return PARSE_SUCCEEDED;
            }
        return PARSE_INCOMPLETE;
        }

    /**
       The patch base address a block at <tt>address</tt> belongs to, or -1.
       Recognised bases are the Patch-mode temporary patch, the 128 user patches and the
       sixteen Performance-mode part temporary patches.
    */
    static int patchBaseOf(int address, int size)
        {
        if (isBlockOf(RolandXV5050Sysex.TEMP_PATCH, address, size)) return RolandXV5050Sysex.TEMP_PATCH;
        for (int n = 0; n < PATCHES_PER_BANK; n++)
            {
            int base = RolandXV5050Sysex.userPatch(n);
            if (isBlockOf(base, address, size)) return base;
            }
        for (int part = 0; part < 16; part++)
            {
            int base = RolandXV5050Sysex.TEMP_PART + part * RolandXV5050Sysex.PART_STRIDE;
            if (isBlockOf(base, address, size)) return base;
            }
        return -1;
        }

    static boolean isBlockOf(int base, int address, int size)
        {
        return address >= base && blockIndexOf(address - base, size) >= 0;
        }

    /** The index in {@link RolandXV5050Params#PATCH} of the block at this offset and size, or -1. */
    static int blockIndexOf(int offset, int size)
        {
        for (int i = 0; i < RolandXV5050Params.PATCH.length; i++)
            {
            RolandXV5050Params.Block b = RolandXV5050Params.PATCH[i];
            if (offset == (b.address << 7) && size == b.size) return i;
            }
        return -1;
        }

    // ======================================================================================
    // Emitting

    public boolean getSendsAllParametersAsDump() { return true; }

    public Object[] emitAll(Model tempModel, boolean toWorkingMemory, boolean toFile)
        {
        if (tempModel == null) tempModel = getModel();

        // Saved files carry the temporary-patch address, so loading one into the synth
        // auditions the patch instead of overwriting a user slot.
        int base = (toWorkingMemory || toFile)
            ? RolandXV5050Sysex.TEMP_PATCH
            : RolandXV5050Sysex.userPatch(tempModel.get("number", 0));

        java.util.List<Object> out = new ArrayList<>();
        if (!toFile)
            {
            // 1F 00 00 00 is the patch edit buffer only in Patch mode.
            out.add(patchModeMessage());
            out.add(Integer.valueOf(PAUSE_AFTER_MODE_SWITCH));
            }
        for (int i = 0; i < RolandXV5050Params.PATCH.length; i++)
            {
            if (i > 0 && !toFile) out.add(Integer.valueOf(PAUSE_BETWEEN_BLOCKS));
            out.add(blockMessage(RolandXV5050Params.PATCH[i], base));
            }
        return out.toArray();
        }

    /** One block of the current model as a DT1 at <tt>base</tt>. */
    byte[] blockMessage(RolandXV5050Params.Block block, int base)
        {
        byte[] data = new byte[block.size];
        if (block == COMMON_BLOCK)
            {
            String name = revisePatchName(model.get("name", ""));
            for (int i = 0; i < RolandXV5050Params.NAME_LENGTH; i++)
                data[i] = (byte)(name.charAt(i) & 0x7F);
            }
        for (RolandXV5050Params.P p : block.params)
            {
            byte[] v = RolandXV5050Sysex.encode(p, model.get(p.key, p.def));
            System.arraycopy(v, 0, data, p.offset, v.length);
            }
        return RolandXV5050Sysex.dt1(getID(), base + (block.address << 7), data);
        }

    /** Switch the synth to Patch mode: Setup Sound Mode = PATCH. */
    byte[] patchModeMessage()
        {
        return RolandXV5050Sysex.dt1(getID(), RolandXV5050Sysex.SETUP, RolandXV5050Sysex.MODE_PATCH);
        }

    public Object[] emitAll(String key)
        {
        if (key.equals("bank") || key.equals("number")) return new Object[0];

        if (key.equals("name"))
            {
            String name = revisePatchName(model.get("name", ""));
            byte[] data = new byte[RolandXV5050Params.NAME_LENGTH];
            for (int i = 0; i < data.length; i++) data[i] = (byte)(name.charAt(i) & 0x7F);
            return new Object[] { RolandXV5050Sysex.dt1(getID(),
                RolandXV5050Sysex.TEMP_PATCH + (COMMON_BLOCK.address << 7), data) };
            }

        RolandXV5050Params.P p = BY_KEY.get(key);
        if (p == null) return new Object[0];
        RolandXV5050Params.Block block = BLOCK_OF_KEY.get(key);

        // A nibbled parameter goes out as all of its bytes in one DT1 at its first address.
        int address = RolandXV5050Sysex.TEMP_PATCH + (block.address << 7) + p.offset;
        return new Object[] { RolandXV5050Sysex.dt1(getID(), address,
            RolandXV5050Sysex.encode(p, model.get(p.key, p.def))) };
        }

    // ======================================================================================
    // Requesting

    /**
       Read the patch the synth is playing now.

       <p>Note that 1F 00 00 00 only exists when a <i>patch</i> is selected. With a
       rhythm set selected -- bank 86 or 120 -- the synth answers nothing at all, and
       the request appears to time out. Verified on the hardware, 2026-11-15.
    */
    public byte[] requestCurrentDump()
        {
        // 1F 00 00 00 is the patch edit buffer only in Patch mode.
        tryToSendSysex(patchModeMessage());
        simplePause(PAUSE_AFTER_MODE_SWITCH);
        return requestPatch(RolandXV5050Sysex.TEMP_PATCH);
        }

    public byte[] requestDump(Model tempModel)
        {
        if (tempModel == null) tempModel = getModel();
        // changePatch() has already put us in Patch mode and selected the patch, so read
        // the temporary patch -- preset banks are not addressable over sysex.
        return requestPatch(RolandXV5050Sysex.TEMP_PATCH);
        }

    /**
       One RQ1 covering the whole patch. The right size is the address span
       (00 00 27 09), not the sum of the block sizes.
    */
    byte[] requestPatch(int base)
        {
        if (REQUEST_WHOLE_PATCH_AT_ONCE)
            return RolandXV5050Sysex.rq1(getID(), base, RolandXV5050Params.PATCH_SPAN);

        // Fallback: one request per block, the first here and the rest sent directly.
        for (int i = 1; i < RolandXV5050Params.PATCH.length; i++)
            {
            RolandXV5050Params.Block b = RolandXV5050Params.PATCH[i];
            tryToSendSysex(RolandXV5050Sysex.rq1(getID(), base + (b.address << 7), b.size));
            simplePause(PAUSE_BETWEEN_BLOCKS);
            }
        RolandXV5050Params.Block first = RolandXV5050Params.PATCH[0];
        return RolandXV5050Sysex.rq1(getID(), base + (first.address << 7), first.size);
        }

    public boolean getAlwaysChangesPatchesOnRequestDump() { return true; }

    public void changePatch(Model tempModel)
        {
        int bank = tempModel.get("bank", 0);
        int number = tempModel.get("number", 0);
        if (bank < 0 || bank >= BANKS.length) bank = 0;

        model.set("bank", bank);
        model.set("number", number);

        try
            {
            tryToSendSysex(patchModeMessage());
            simplePause(PAUSE_AFTER_MODE_SWITCH);
            tryToSendMIDI(new ShortMessage(ShortMessage.CONTROL_CHANGE, getChannelOut(), 0, BANK_MSB[bank]));
            tryToSendMIDI(new ShortMessage(ShortMessage.CONTROL_CHANGE, getChannelOut(), 32, BANK_LSB[bank]));
            tryToSendMIDI(new ShortMessage(ShortMessage.PROGRAM_CHANGE, getChannelOut(), number, 0));
            }
        catch (Exception e) { Synth.handleException(e); }
        }


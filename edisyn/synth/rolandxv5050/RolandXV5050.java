    public String getPatchLocationName(Model model)
        {
        if (!model.exists("number") || !model.exists("bank")) return null;
        int bank = model.get("bank");
        if (bank < 0 || bank >= BANKS.length) bank = 0;
        return BANKS[bank] + String.format("%03d", model.get("number") + 1);
        }

    public Model getNextPatchLocation(Model model)
        {
        int bank = model.get("bank");
        int number = model.get("number") + 1;
        if (number >= PATCHES_PER_BANK)
            {
            number = 0;
            bank++;
            if (bank >= BANKS.length) bank = 0;
            }
        Model next = buildModel();
        next.set("bank", bank);
        next.set("number", number);
        return next;
        }

    public boolean patchLocationEquals(Model a, Model b)
        {
        return a.get("bank", -1) == b.get("bank", -2) && a.get("number", -1) == b.get("number", -2);
        }

    /**
       Wave numbers are modelled over the manual's full 0...16384, because factory
       patches carry expansion wave numbers in switched-off tones and clamping them
       would alter the patch. Mutation, though, should only ever land on a wave this
       editor can name.
    */
    public int reviseMutatedValue(String key, int oldValue, int proposedValue, Model model)
        {
        RolandXV5050Params.P p = BY_KEY.get(key);
        if (p != null && p.kind == RolandXV5050Params.KIND_WAVE && proposedValue > RolandXV5050Params.WAVE_MAX)
            return RolandXV5050Params.WAVE_MAX;
        return proposedValue;
        }

    public boolean gatherPatchInfo(String title, Model change, boolean writing)
        {
        String[] banks = writing ? new String[] { BANKS[BANK_USER] } : BANKS;
        JComboBox bank = new JComboBox(banks);
        int b = model.get("bank", 0);
        if (b >= banks.length) b = 0;
        bank.setSelectedIndex(b);

        JTextField number = new SelectedTextField("" + (model.get("number", 0) + 1), 3);

        while (true)
            {
            boolean result = showMultiOption(this, new String[] { "Bank", "Patch Number" },
                new JComponent[] { bank, number }, title, "Enter the bank and patch number.");
            if (!result) return false;

            int n;
            try { n = Integer.parseInt(number.getText()); }
            catch (NumberFormatException e) { n = -1; }
            if (n < 1 || n > PATCHES_PER_BANK)
                {
                showSimpleError(title, "The patch number must be an integer 1..." + PATCHES_PER_BANK + ".");
                continue;
                }
            change.set("bank", writing ? BANK_USER : bank.getSelectedIndex());
            change.set("number", n - 1);
            return true;
            }
        }
